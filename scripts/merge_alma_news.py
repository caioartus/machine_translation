"""Merge the cleaned ALMA and News training files, preserving their rows and IDs.

Run: python scripts/merge_alma_news.py
Paths are resolved from the script location; no personal paths or arguments needed.
Outputs: data/processed/alma_news_train.jsonl and alma_news_merge_report.md.
"""

from collections import Counter
from pathlib import Path

from audit_news_alma_overlap import audit_overlap, check_paths, sha256_file
from data_utils import read_jsonl, write_jsonl


REPO_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = REPO_ROOT / "data/processed"
ALMA_PATH = DATA_DIR / "alma_train.jsonl"
NEWS_PATH = DATA_DIR / "news_commentary_train.jsonl"
OUTPUT_PATH = DATA_DIR / "alma_news_train.jsonl"
REPORT_PATH = DATA_DIR / "alma_news_merge_report.md"


def merge_rows(alma, news):
    """Validate inputs and return ALMA rows followed by News rows."""
    for name, rows in [("ALMA", alma), ("News", news)]:
        if not rows:
            raise ValueError(f"{name} input is empty")
        for number, row in enumerate(rows, 1):
            if not isinstance(row, dict) or any(
                not isinstance(row.get(field), str) or not row[field].strip()
                for field in ("id", "source", "zh", "en")
            ):
                raise ValueError(f"{name} row {number}: id/source/zh/en must be nonempty strings")

    merged = alma + news
    ids = Counter(row["id"] for row in merged)
    duplicates = [row_id for row_id, count in ids.items() if count > 1]
    if duplicates:
        raise ValueError(f"Duplicate IDs: {duplicates[:5]}")
    overlaps, _ = audit_overlap(alma, news)
    if overlaps:
        raise ValueError(
            f"Found {len(overlaps)} overlapping News rows; run "
            "scripts/audit_news_alma_overlap.py and resolve overlap before merging"
        )
    return merged


def main():
    check_paths([ALMA_PATH, NEWS_PATH])
    alma = read_jsonl(ALMA_PATH)
    news = read_jsonl(NEWS_PATH)
    try:
        merged = merge_rows(alma, news)
    except ValueError as error:
        raise SystemExit(str(error)) from error

    input_hashes = {path: sha256_file(path) for path in (ALMA_PATH, NEWS_PATH)}
    write_jsonl(merged, OUTPUT_PATH)
    lines = [
        "# ALMA + News training merge report",
        "",
        "Generated by `scripts/merge_alma_news.py`.",
        "Original rows, IDs, source labels and text are preserved. ALMA rows come first, "
        "followed by News rows; no resampling or proportion adjustment is applied.",
        "",
        "| Input | Rows | SHA-256 |",
        "|---|---:|---|",
    ]
    for path, rows in ((ALMA_PATH, alma), (NEWS_PATH, news)):
        lines.append(
            f"| `{path.relative_to(REPO_ROOT).as_posix()}` | {len(rows):,} | "
            f"`{input_hashes[path]}` |"
        )
    lines += [
        "",
        f"- Output: `{OUTPUT_PATH.relative_to(REPO_ROOT).as_posix()}`",
        f"- Total rows: **{len(merged):,}**",
        f"- Output SHA-256: `{sha256_file(OUTPUT_PATH)}`",
        "- Duplicate IDs: 0",
        "- Cross-corpus exact or loose Chinese-source overlaps: 0",
        "",
        "This file contains training data only. Dev and test files are unchanged. "
        "Difficulty features and training integration must be prepared separately.",
    ]
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"ALMA rows: {len(alma):,}")
    print(f"News rows: {len(news):,}")
    print(f"Merged rows: {len(merged):,}")
    print(f"saved data: {OUTPUT_PATH}")
    print(f"saved report: {REPORT_PATH}")


if __name__ == "__main__":
    main()
