"""Step 5 of data preparation: record the difficulty groups (bins) and show where data falls.

The bin edges themselves are defined in data_utils.py (LENGTH_EDGES, RARITY_EDGES), so that
the training sampler and the evaluation code use exactly the same definition. This script:
  1. saves the definition to data/features/bins.json (a record of what was used), and
  2. reports how ALMA train and each test set are distributed over the bins and cells.

Why these edges (decided from data/features/*.csv; numbers are shares of ALMA train):
  - Length (source subword tokens): short <= 15 (10%) | 16-30 (35%) | 31-60 (45%) | > 60 (10%).
    The short bin covers ~95% of the official Tatoeba test set (its 95th percentile is 13
    tokens); the long bin is the symmetric ~10% tail at the other end.
  - Rarity (rarity_mean, nats per subword): typical <= 7.9 < rare (12%). 7.9 is about the
    90th percentile of ALMA train, rounded and then fixed. Only 2 rarity levels: with 3 levels
    (adding "common"), some cells are empty in a 1,000-example training subset.
  - Edges are FIXED numbers, not quantiles of each subset: equal-count (quantile) bins would
    make every bin equally frequent, and balancing them would then change nothing.

Outputs (in data/features/):
    bins.json          - edges, labels and feature names of the bins
    bins_report.md     - share of each split in each bin / cell (for the project report)
    bins_heatmap.png   - the same for ALMA train and the two official test sets, as a picture

Run from the repository root (after compute_difficulty.py):
    python scripts/make_bins.py
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")  # draw to files, no window needed (also works on the cluster)
import matplotlib.pyplot as plt
import pandas as pd

from data_utils import (LENGTH_EDGES, LENGTH_LABELS, RARITY_EDGES, RARITY_LABELS,
                        all_cells, assign_bins)

FEAT_DIR = Path("data/features")
SPLITS = {  # file name -> name used in tables
    "alma_train": "ALMA train",
    "alma_dev": "ALMA dev",
    "wmt22_test": "WMT22 (official)",
    "tatoeba_test": "Tatoeba (official)",
    "tatoeba_challenge_test": "Tatoeba Challenge (suppl.)",
}


def shares(df, column, labels):
    """Percentage of rows in each category of `column`, in the order of `labels`."""
    return (df[column].value_counts(normalize=True).reindex(labels, fill_value=0) * 100)


def main():
    data = {name: assign_bins(pd.read_csv(FEAT_DIR / f"{split}.csv"))
            for split, name in SPLITS.items()}

    # --- 1. Record the definition -------------------------------------------------
    definition = {
        "length": {"feature": "src_len", "upper_edges_inclusive": LENGTH_EDGES,
                   "labels": LENGTH_LABELS},
        "rarity": {"feature": "rarity_mean", "upper_edges_inclusive": RARITY_EDGES,
                   "labels": RARITY_LABELS},
        "cells": all_cells(),
    }
    with open(FEAT_DIR / "bins.json", "w") as f:
        json.dump(definition, f, indent=2)

    # --- 2. Tables: share of each split in each bin and cell -----------------------
    def table(column, labels):
        rows = ["| | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
        for name, df in data.items():
            rows.append(f"| {name} (n={len(df)}) | "
                        + " | ".join(f"{v:.1f}" for v in shares(df, column, labels)) + " |")
        return rows

    lines = [
        "# Difficulty groups (bins)",
        "",
        "Generated by `scripts/make_bins.py`; edges defined in `scripts/data_utils.py`.",
        "",
        "- **Length** (`src_len`, M2M-100 subword tokens of the Chinese source): "
        f"short ≤ {LENGTH_EDGES[0]} < mid_short ≤ {LENGTH_EDGES[1]} < mid_long ≤ {LENGTH_EDGES[2]} < long.",
        f"- **Rarity** (`rarity_mean`, average −log p per source subword, nats): "
        f"typical ≤ {RARITY_EDGES[0]} < rare.",
        "- **Cell** = length bin × rarity bin (8 cells). The length-balanced condition uses the "
        "4 length bins; the joint condition uses the 8 cells.",
        "- Edges are fixed numbers chosen once on the full ALMA training pool and reused for every "
        "training-set size and for the evaluation breakdowns.",
        "",
        "## Share of each split per length bin (%)",
        "",
        *table("length_bin", LENGTH_LABELS),
        "",
        "## Share of each split per rarity bin (%)",
        "",
        *table("rarity_bin", RARITY_LABELS),
        "",
        "## Share of each split per cell (%)",
        "",
        *table("cell", all_cells()),
        "",
        "## Reading",
        "",
        "- **Length:** both official test sets are concentrated in the short bin, which holds "
        "only 10% of ALMA train (WMT22 28%, Tatoeba 97%). Long sentences are about as frequent "
        "in WMT22 as in ALMA train, and absent from Tatoeba.",
        "- **Rarity:** both test sets have about twice ALMA train's share of rare sentences "
        "(WMT22 30%, Tatoeba 23% vs 12%). But ALMA dev, which comes from the same corpus, also "
        "has 24%: any newer text brings names and terms unseen in training. Rarity counts use "
        "leave-one-out for training sentences, so this is not a counting artefact. Compared with "
        "dev, WMT22 is only somewhat rarer and Tatoeba is not rarer at all.",
    ]
    with open(FEAT_DIR / "bins_report.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # --- 3. Heatmap: one panel per split, length bins (rows) x rarity bins (columns) ---
    shown = ["ALMA train", "WMT22 (official)", "Tatoeba (official)"]
    fig, axes = plt.subplots(1, len(shown), figsize=(4 * len(shown), 4))
    for ax, name in zip(axes, shown):
        grid = (pd.crosstab(data[name]["length_bin"], data[name]["rarity_bin"], normalize=True)
                .reindex(index=LENGTH_LABELS, columns=RARITY_LABELS, fill_value=0) * 100)
        ax.imshow(grid.values, cmap="Blues", vmin=0, vmax=60)
        for i in range(len(LENGTH_LABELS)):
            for j in range(len(RARITY_LABELS)):
                v = grid.values[i, j]
                ax.text(j, i, f"{v:.1f}%", ha="center", va="center",
                        color="white" if v > 35 else "black")
        ax.set_xticks(range(len(RARITY_LABELS)), RARITY_LABELS)
        ax.set_yticks(range(len(LENGTH_LABELS)),
                      [f"{l}\n(≤{e})" if e else f"{l}\n(>{LENGTH_EDGES[-1]})"
                       for l, e in zip(LENGTH_LABELS, LENGTH_EDGES + [None])])
        ax.set_title(f"{name}\n(n={len(data[name])})")
    fig.suptitle("Share of sentences per cell (source length × vocabulary rarity)")
    fig.tight_layout()
    fig.savefig(FEAT_DIR / "bins_heatmap.png", dpi=120)

    print((FEAT_DIR / "bins_report.md").read_text(encoding="utf-8"))
    print(f"Saved bins.json, bins_report.md and bins_heatmap.png to {FEAT_DIR}/")


if __name__ == "__main__":
    main()
