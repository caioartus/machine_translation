"""Audit overlap between the cleaned ALMA and News Commentary training sets.

This script is read-only with respect to both training files.  It records any
News row whose Chinese source or complete (Chinese, English) pair already occurs
in ALMA train. Paths are resolved from this script's location, so the command can
be run from any directory and from any user's checkout::

    python scripts/audit_news_alma_overlap.py

Outputs:
    data/audit/news_alma_overlap.jsonl
    data/audit/news_alma_overlap_report.md
"""

import hashlib
import re
from collections import Counter, defaultdict
from pathlib import Path

from data_utils import normalize, read_jsonl, write_jsonl


REPO_ROOT = Path(__file__).resolve().parents[1]
ALMA_PATH = REPO_ROOT / "data/processed/alma_train.jsonl"
NEWS_PATH = REPO_ROOT / "data/processed/news_commentary_train.jsonl"
OVERLAP_PATH = REPO_ROOT / "data/audit/news_alma_overlap.jsonl"
REPORT_PATH = REPO_ROOT / "data/audit/news_alma_overlap_report.md"

MATCH_DESCRIPTIONS = {
    "exact_pair": "Normalised Chinese and English are both identical",
    "exact_source_different_target": (
        "Normalised Chinese is identical but the English translation differs"
    ),
    "loose_source": (
        "Chinese matches after lowercasing and removing punctuation, underscores and spaces"
    ),
}


def loose(text):
    """Near-exact source key, identical to the test-set leakage check."""
    return re.sub(r"[\W_]+", "", text.lower())


def sha256_file(path, chunk_size=1024 * 1024):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(chunk_size), b""):
            digest.update(chunk)
    return digest.hexdigest()


def check_paths(paths):
    missing = [path for path in paths if not path.is_file()]
    if missing:
        joined = "\n  ".join(str(path) for path in missing)
        raise SystemExit("Missing required input file(s):\n  " + joined)


def validate_rows(rows, name):
    required = {"id", "zh", "en"}
    for line_number, row in enumerate(rows, 1):
        missing = required - row.keys()
        if missing:
            raise SystemExit(
                f"{name} line {line_number} is missing field(s): "
                + ", ".join(sorted(missing))
            )


def audit_overlap(alma_rows, news_rows):
    """Return one audit row per overlapping News row plus match-type counts."""
    validate_rows(alma_rows, "ALMA")
    validate_rows(news_rows, "News Commentary")

    pair_index = defaultdict(list)
    source_index = defaultdict(list)
    loose_index = defaultdict(list)
    alma_normalised = {}

    for row in alma_rows:
        zh, en = normalize(row["zh"]), normalize(row["en"])
        item = {"id": row["id"], "zh": zh, "en": en}
        alma_normalised[row["id"]] = item
        pair_index[(zh, en)].append(row["id"])
        source_index[zh].append(row["id"])
        if loose(zh):
            loose_index[loose(zh)].append(row["id"])

    overlaps = []
    counts = Counter()
    for row in news_rows:
        zh, en = normalize(row["zh"]), normalize(row["en"])
        pair_ids = pair_index.get((zh, en), [])
        source_ids = source_index.get(zh, [])
        loose_ids = loose_index.get(loose(zh), []) if loose(zh) else []

        if pair_ids:
            match, alma_ids = "exact_pair", pair_ids
        elif source_ids:
            match, alma_ids = "exact_source_different_target", source_ids
        elif loose_ids:
            match, alma_ids = "loose_source", loose_ids
        else:
            continue

        counts[match] += 1
        overlaps.append(
            {
                "news_id": row["id"],
                "match": match,
                "zh": zh,
                "news_en": en,
                "alma_matches": [alma_normalised[alma_id] for alma_id in alma_ids],
            }
        )

    return overlaps, counts


def write_report(alma_rows, news_rows, overlaps, counts, alma_sha256, news_sha256):
    alma_display = ALMA_PATH.relative_to(REPO_ROOT)
    news_display = NEWS_PATH.relative_to(REPO_ROOT)
    overlap_display = OVERLAP_PATH.relative_to(REPO_ROOT)
    lines = [
        "# ALMA–News Commentary training overlap audit",
        "",
        "Generated by `scripts/audit_news_alma_overlap.py`. This audit does not modify "
        "either training file.",
        "",
        "## Inputs",
        "",
        f"- ALMA: `{alma_display}` — {len(alma_rows):,} rows — SHA-256 `{alma_sha256}`",
        f"- News: `{news_display}` — {len(news_rows):,} rows — SHA-256 `{news_sha256}`",
        "",
        "## Results",
        "",
        "Each News row is counted once under the strongest match type.",
        "",
        "| Match type | Description | News rows |",
        "|---|---|---:|",
    ]
    for match, description in MATCH_DESCRIPTIONS.items():
        lines.append(f"| `{match}` | {description} | {counts[match]:,} |")
    lines += [
        f"| **Total** | News rows overlapping ALMA train | **{len(overlaps):,}** |",
        "",
        f"Full audit: `{overlap_display}`.",
        "",
    ]
    if overlaps:
        lines.append(
            "Before creating an ALMA + News training pool, remove these News rows and "
            "deterministically replace them from the cleaned candidate pool."
        )
    else:
        lines.append("No ALMA-train overlap was found; the current 15,000 News rows can be used.")

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    check_paths([ALMA_PATH, NEWS_PATH])
    alma_sha256 = sha256_file(ALMA_PATH)
    news_sha256 = sha256_file(NEWS_PATH)
    alma_rows = read_jsonl(ALMA_PATH)
    news_rows = read_jsonl(NEWS_PATH)
    overlaps, counts = audit_overlap(alma_rows, news_rows)

    write_jsonl(overlaps, OVERLAP_PATH)
    write_report(alma_rows, news_rows, overlaps, counts, alma_sha256, news_sha256)

    print(f"ALMA rows: {len(alma_rows):,}")
    print(f"News rows: {len(news_rows):,}")
    for match in MATCH_DESCRIPTIONS:
        print(f"{match}: {counts[match]:,}")
    print(f"total overlapping News rows: {len(overlaps):,}")
    print(f"saved audit: {OVERLAP_PATH}")
    print(f"saved report: {REPORT_PATH}")


if __name__ == "__main__":
    main()
