"""Step 6 of data preparation: fix the training subsets for the training-set-size experiments.

For each seed, the cleaned ALMA training ids are shuffled once, and a subset of size n is
simply the FIRST n ids of that shuffled list. This makes the subsets NESTED
(1k is inside 2k, which is inside 5k, which is inside the full set): going from one size to
the next only ADDS data, so differences between sizes are not blurred by also swapping
which examples are used.

Each seed gives a different shuffle, so repeating an experiment over seeds also repeats it
over different draws of the training data (important at 1k, where the draw matters most).
Suggested convention: run seed s on the subsets of seed s.

Subsets are plain random draws (not stratified by bin), so each subset keeps the natural
mix of easy and hard examples; the sampling conditions then reweight it during training.
A subset is refused if any of the 8 cells is empty, since the joint condition needs every cell.

Outputs (in data/subsets/):
    seed{S}_n{N}.txt     - one training id per line (e.g. seed0_n1000.txt); "full" for all
    subsets_report.md    - number of examples per cell in every subset

Run from the repository root (after compute_difficulty.py):
    python scripts/make_subsets.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

from data_utils import all_cells, assign_bins

FEATURES = Path("data/features/alma_train.csv")
OUT_DIR = Path("data/subsets")
SIZES = [1000, 2000, 5000]  # plus the full training set
SEEDS = [0, 1, 2]


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    train = assign_bins(pd.read_csv(FEATURES)).set_index("id")
    n_full = len(train)

    lines = [
        "# Training subsets",
        "",
        "Generated by `scripts/make_subsets.py`. Nested random subsets of the cleaned ALMA "
        f"training set ({n_full} pairs): for each seed, the ids are shuffled once and a subset "
        "of size n is the first n ids.",
        "",
        "Number of examples per cell (length bin / rarity bin):",
        "",
        "| Subset | " + " | ".join(all_cells()) + " | smallest cell |",
        "|---|" + "---|" * (len(all_cells()) + 1),
    ]

    for seed in SEEDS:
        # One fixed shuffle per seed; every subset of this seed is a prefix of it.
        order = np.random.default_rng(seed).permutation(train.index.to_numpy())
        for n in SIZES + [n_full]:
            ids = order[:n]
            counts = train.loc[ids, "cell"].value_counts().reindex(all_cells(), fill_value=0)
            if counts.min() == 0:
                raise SystemExit(f"seed {seed}, n={n}: empty cell(s) "
                                 f"{list(counts[counts == 0].index)}; choose other bins or sizes")

            name = f"seed{seed}_n{'full' if n == n_full else n}"
            (OUT_DIR / f"{name}.txt").write_text("\n".join(ids) + "\n", encoding="utf-8")
            lines.append(f"| {name} | " + " | ".join(str(c) for c in counts)
                         + f" | {counts.min()} |")
            print(f"{name}: {n} ids, smallest cell {counts.min()} ({counts.idxmin()})")

    with open(OUT_DIR / "subsets_report.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Saved to {OUT_DIR}/")


if __name__ == "__main__":
    main()
